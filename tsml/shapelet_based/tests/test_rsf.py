def test_rsf_classifier_matches_wildboar():
    """Test predictions match those of wildboar 1.2.0 using the same trees.

    Expected values were generated by fitting wildboar ShapeletTreeClassifier
    estimators with the case weights and seeds used by this forest.
    """
    X_train, y_train = load_minimal_chinatown("TRAIN")
    X_test, _ = load_minimal_chinatown("TEST")

    rsf = RandomShapeletForestClassifier(n_estimators=5, random_state=0)
    rsf.fit(X_train, y_train)
    proba = rsf.predict_proba(X_test)

    expected = np.array(
        [0.8, 0.8, 0.6, 1.0, 1.0, 1.0, 0.8, 0.8, 0.6, 0.8]
        + [0.2, 0.2, 0.8, 0.0, 0.2, 0.8, 0.2, 0.2, 0.2, 0.4]
    )
    np.testing.assert_array_equal(proba[:, 0], expected)


